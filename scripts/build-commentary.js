/** Compile editorially approved first-level Markdown commentaries into static data. */
const fs = require("fs");
const path = require("path");
const matter = require("gray-matter");

const root = path.resolve(__dirname, "..");
const articlesDir = path.join(root, "articles");
const commentaryDir = path.join(root, "commentary");
const output = path.join(root, "js", "commentary-data.js");

const articles = new Map();
for (const filename of fs.readdirSync(articlesDir).filter(name => name.endsWith(".md") && !name.startsWith("_"))) {
  const id = path.basename(filename, ".md");
  const { data } = matter(fs.readFileSync(path.join(articlesDir, filename), "utf8"));
  articles.set(id, { commentaryEnabled: data.commentary !== false });
}

function countWords(markdown) {
  // Count visible words, excluding Markdown formatting and link destinations.
  const plain = markdown
    .replace(/```(?:[^\n]*)\n?/g, " ")
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/<[^>]*>/g, " ")
    .replace(/[`*_#~>|]/g, " ");
  return plain.trim() ? plain.trim().split(/\s+/u).length : 0;
}

function validDate(value) {
  return typeof value === "string" && /^\d{4}-\d{2}-\d{2}$/.test(value) &&
    !Number.isNaN(Date.parse(value + "T00:00:00Z")) &&
    new Date(value + "T00:00:00Z").toISOString().slice(0, 10) === value;
}

const commentaries = fs.readdirSync(commentaryDir)
  .filter(name => name.endsWith(".md") && !name.startsWith("_"))
  .map(filename => {
    const id = path.basename(filename, ".md");
    const { data, content } = matter(fs.readFileSync(path.join(commentaryDir, filename), "utf8"));
    for (const field of ["title", "author", "article", "date", "excerpt"]) {
      if (typeof data[field] !== "string" || !data[field].trim()) {
        throw new Error(`${filename}: missing/invalid ${field} (must be a nonempty quoted string)`);
      }
    }
    if (!validDate(data.date)) throw new Error(`${filename}: date must be YYYY-MM-DD`);
    if (!articles.has(data.article)) {
      throw new Error(`${filename}: article '${data.article}' is not an existing original essay ID`);
    }
    if (!articles.get(data.article).commentaryEnabled) {
      throw new Error(`${filename}: original article '${data.article}' has commentary disabled`);
    }
    const wordCount = countWords(content);
    if (!wordCount || wordCount > 1000) {
      throw new Error(`${filename}: commentary must have 1–1000 words; found ${wordCount}`);
    }
    return {
      id,
      articleId: data.article,
      title: data.title.trim(),
      author: data.author.trim(),
      date: data.date,
      excerpt: data.excerpt.trim(),
      wordCount,
      content: content.trim()
    };
  }).sort((a, b) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title));

fs.writeFileSync(output,
  `// GENERATED BY npm run build; DO NOT EDIT.\nconst COMMENTARIES = ${JSON.stringify(commentaries, null, 2)};\n`);
console.log(`Built commentary index with ${commentaries.length} approved commentary piece(s).`);
